/* eslint-disable @typescript-eslint/no-unused-expressions -- Playwright CLI evaluates this function expression. */
async page => {
  await page.goto('http://127.0.0.1:3302/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('textbox', { name: 'Tu propuesta', exact: true }).fill('Proponemos un piloto de soporte con un presupuesto de 500 unidades y revisión humana.');
  await page.getByRole('button', { name: 'Enviar mensaje', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Autoriz' }).waitFor();
  await page.getByRole('checkbox', { name: /Autorizo/ }).check();
  await page.getByRole('button', { name: 'Enviar mensaje', exact: true }).click();
  await page.getByRole('textbox', { name: 'Título de la propuesta', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('#proposal-title')?.value === 'Piloto de soporte');
  await page.locator('input[type=file]').setInputFiles('evals/fixtures/source.md');
  await page.getByText('source.md', { exact: true }).waitFor();
  await page.request.post('http://127.0.0.1:8767/control/fail-next');
  await page.getByRole('button', { name: 'Generar revisión', exact: true }).click();
  await page.waitForURL(/\/reviews\//);
  await page.getByRole('alert').waitFor();
  await page.getByRole('button', { name: 'Continuar o reintentar', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.new-stage')?.textContent.includes('Completa'));
  const citation = page.getByRole('button', { name: /Inspeccionar pasaje/ }).first();
  await citation.click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  if (!(await citation.evaluate(element => element === document.activeElement))) throw new Error('Citation focus was not restored');
  if (await page.locator('input[type=radio]:checked').count()) throw new Error('Decision was preselected');
  await page.getByRole('radio', { name: 'Posponer', exact: true }).check();
  await page.getByRole('textbox', { name: 'Fundamento', exact: true }).fill('Falta medir el costo de revisión humana.');
  await page.getByRole('button', { name: 'Guardar decisión', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Decisión guardada' }).waitFor();
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#decision-rationale')?.value === 'Falta medir el costo de revisión humana.');
  await page.getByRole('textbox', { name: 'Fundamento', exact: true }).fill('Corrección: medir costos y errores.');
  await page.getByRole('button', { name: 'Corregir decisión', exact: true }).click();
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  await page.getByRole('heading', { name: 'Human decision', exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.new-rail').getBoundingClientRect().right <= 0);
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile horizontal overflow');
  await page.screenshot({ path: '.playwright-cli/integration-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.waitForFunction(() => document.querySelector('.new-rail').getBoundingClientRect().left === 0);
  await page.screenshot({ path: '.playwright-cli/integration-desktop.png' });
  await page.getByRole('link', { name: 'Saved reviews', exact: true }).click();
  await page.getByRole('heading', { name: 'Saved reviews', exact: true }).waitFor();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete review', exact: true }).first().click();
  await page.getByText('No saved reviews yet.', { exact: true }).waitFor();
}
